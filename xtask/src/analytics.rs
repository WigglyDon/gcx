//! Exercise the donor's Android-only analytics callback without borrowing a phone.
//! Only this translation unit takes the Android branch; this is a host regression.
use std::path::Path;
use std::process::{Command, Stdio};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

fn quote(path: &Path) -> Result<String> {
    let path = path.to_str().ok_or("non-UTF8 regression path")?;
    Ok(format!("'{}'", path.replace('\'', "'\\''")))
}

fn generated_command(build: &Path, target: &str) -> Result<String> {
    let output = Command::new("ninja")
        .arg("-C")
        .arg(build)
        .args(["-t", "commands", "-s", target])
        .output()?;
    let text = String::from_utf8(output.stdout)?;
    if !output.status.success() || text.lines().count() != 1 {
        return Err("expected one command from the existing host Ninja graph".into());
    }
    Ok(text.trim().to_owned())
}

fn execute(build: &Path, log: &Path, command: &str) -> Result<()> {
    let file = std::fs::File::create_new(log)?;
    let status = Command::new("timeout")
        .args(["120", "nice", "-n", "10", "sh", "-c", command])
        .current_dir(build)
        .stdout(Stdio::from(file.try_clone()?))
        .stderr(Stdio::from(file))
        .status()?;
    if !status.success() {
        return Err(format!("regression failed ({status}); see {}", log.display()).into());
    }
    Ok(())
}

pub fn check(root: &Path, source: &Path) -> Result<()> {
    let build = root.join("build/host");
    let probe = root.join("target/debug/gcx-probe");
    if !probe.is_file() || !build.join("gcx/libgcx_engine.so").is_file() {
        return Err("build the normal host engine and Rust gcx-probe first".into());
    }
    let stamp = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)?
        .as_nanos();
    let scratch = root.join(format!(
        ".local/android-analytics-{stamp}-{}",
        std::process::id()
    ));
    std::fs::create_dir(&scratch)?;
    // Preinclude the real host window declarations before selecting ANDROID. The
    // analytics translation unit then uses its real Android API/implementation,
    // without compiling Android window ownership against a host libc.
    let prefix = scratch.join("analytics-only.h");
    std::fs::write(
        &prefix,
        "#include \"Common/WindowSystemInfo.h\"\n#define ANDROID\n",
    )?;
    const OBJECT: &str = "Source/Core/Core/CMakeFiles/core.dir/DolphinAnalytics.cpp.o";
    let object = scratch.join("DolphinAnalytics.android.o");
    let compile = generated_command(&build, OBJECT)?;
    if !compile.contains(&format!(" -o {OBJECT} ")) {
        return Err("unrecognized host analytics compile command".into());
    }
    // The commands are generated by this checkout's trusted CMake/Ninja graph,
    // never taken from game metadata. Quote every task-created path for the shell.
    let compile = format!(
        "{} -Werror -include {}",
        compile.replace(OBJECT, &quote(&object)?),
        quote(&prefix)?
    );
    std::fs::write(scratch.join("compile-command.txt"), &compile)?;
    execute(&build, &scratch.join("compile.log"), &compile)?;

    let link = generated_command(&build, "gcx/libgcx_engine.so")?;
    const OUTPUT: &str = " -o gcx/libgcx_engine.so ";
    if link.matches(OUTPUT).count() != 1 {
        return Err("unrecognized host native link command".into());
    }
    // Place the variant object before core's archive so the archive's original
    // analytics object is not extracted. All other objects/dependencies are exact
    // existing host build inputs. Never replace the ordinary host library.
    let link = link.replacen(
        OUTPUT,
        &format!(
            " {} -o {} ",
            quote(&object)?,
            quote(&scratch.join("libgcx_engine.so"))?
        ),
        1,
    );
    std::fs::write(scratch.join("link-command.txt"), &link)?;
    execute(&build, &scratch.join("link.log"), &link)?;
    let command = format!(
        "ulimit -c 0 && exec timeout 30 {} {} {}",
        quote(&probe)?,
        quote(&scratch.join("profile"))?,
        quote(&source.join("Data/Sys"))?
    );
    let log = std::fs::File::create_new(scratch.join("probe.log"))?;
    let status = Command::new("sh")
        .args(["-c", &command])
        .current_dir(root)
        .env("LD_LIBRARY_PATH", &scratch)
        .stdout(Stdio::from(log.try_clone()?))
        .stderr(Stdio::from(log))
        .status()?;
    if !status.success() {
        return Err(format!(
            "Android analytics host regression failed: {status}; {}",
            scratch.display()
        )
        .into());
    }
    println!(
        "PASS: absent Android metadata callback, native CPU/input/card barrier/joined teardown; {}",
        scratch.display()
    );
    println!("This host branch regression does not qualify Android gameplay or device boot.");
    Ok(())
}
